#!/usr/bin/env python3
"""Bake the known-good offline host into one Frida script payload.

The flags match analysis/frida_tools/lua_bridge/play_offline.sh and play_mp.sh
for a Crash/Nuketown-style match. Aim-assist number changes are not included.
This script only reads those sources and writes play_runtime.js.
"""
from __future__ import annotations

import json
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
BRIDGE = Path(__file__).resolve().parents[1] / 'bridge'
OUT = HERE / 'play_runtime.js'

# Exact const flips from host_spawn.py for the session that already plays.
REPLACEMENTS = (
    ('const FORCE_LOOPBACK_CHAN = false;', 'const FORCE_LOOPBACK_CHAN = true;'),
    ('const NULL_ENTITY_GUARD = false;', 'const NULL_ENTITY_GUARD = true;'),
    ('const ROUTE_LOCAL_HOST_PACKET = false;', 'const ROUTE_LOCAL_HOST_PACKET = true;'),
    ('const SEND_GAMESTATE = false;', 'const SEND_GAMESTATE = true;'),
    ('const FORCE_OOB_CMD = false;', 'const FORCE_OOB_CMD = true;'),
    ('const BOTS = false;', 'const BOTS = true;'),
    ('const JOIN_ALLIES = false;', 'const JOIN_ALLIES = true;'),
    ('const MATCH_PROBE = false;', 'const MATCH_PROBE = true;'),
    ('const UI_MISSING_NIL = false;', 'const UI_MISSING_NIL = true;'),
    ('const QUIET = false;', 'const QUIET = true;'),
    ('const LOW_OVERHEAD = false;', 'const LOW_OVERHEAD = true;'),
    ('const LUA_ASSET_CACHE = false;', 'const LUA_ASSET_CACHE = true;'),
    ('const UI_RETRY = false;', 'const UI_RETRY = true;'),
    ('const HOST_START_PROPAGATE = false;', 'const HOST_START_PROPAGATE = true;'),
    ('const MP_MODE = -1;', 'const MP_MODE = 211;'),
    ('const STEER_VM53_PIN_PRED = false;', 'const STEER_VM53_PIN_PRED = true;'),
    ('const OBSERVE_VM53_CURSOR = false;', 'const OBSERVE_VM53_CURSOR = true;'),
    ('const OBSERVE_PROTECTED_WRAPPERS = false;', 'const OBSERVE_PROTECTED_WRAPPERS = true;'),
    ('const OMNVAR_ADD = [];', 'const OMNVAR_ADD = ["0x750bd5872bb1d322"];'),
)

LUA_STEPS = (
    (17000, 'hitmarker_scale_state.lua'),
    (18000, 'hitmarker_scale_bind.lua'),
    (19000, 'aa_state.lua'),
    (25000, 'hitmarker_bind_state.lua'),
    (30000, 'hitmarker_bind_state.lua'),
    (45000, 'hitmarker_bind_state.lua'),
    (75000, 'hitmarker_bind_state.lua'),
    (120000, 'hitmarker_bind_state.lua'),
)


def once(source: str, old: str, new: str) -> str:
    count = source.count(old)
    if count != 1:
        raise SystemExit(f'expected one occurrence of {old!r}, found {count}')
    return source.replace(old, new, 1)


def read(name: str) -> str:
    path = BRIDGE / name
    if not path.is_file():
        raise SystemExit(f'missing {path}')
    return path.read_text()


def build_host() -> str:
    source = read('host_spawn.js')
    for old, new in REPLACEMENTS:
        source = once(source, old, new)
    steps = [[delay, read(name)] for delay, name in LUA_STEPS]
    source = once(source, 'const MATCH_LUA_STEPS = null;',
                  'const MATCH_LUA_STEPS = ' + json.dumps(steps) + ';')
    source = once(source, 'rpc.exports=', 'globalThis.wzmHost=')
    # These stay off. Skipping them is part of the known-good match, and the
    # constructor skips are explicitly not a working game.
    for kept in (
        'const BYPASS_STUB53 = false;',
        'const BYPASS_STUB60 = false;',
        'const ENEMY_AI = -1;',
        'const GAMESTATE_RETRY = false;',
    ):
        if kept not in source:
            raise SystemExit('lost required default: ' + kept)
    if 'aim_weapons' in source or 'WZM_AIM_MODE' in source:
        raise SystemExit('aim-assist weapon changes leaked into the host')
    lui = read('lui_send.js').replace('__LUI_SEND_SPEC__', 'class_select:0@22000')
    if '__LUI_SEND_SPEC__' in lui:
        raise SystemExit('class select spec was not substituted')
    gfx = (
        "\nglobalThis.WZM_GFX_ENV=Object.assign({},globalThis.WZM_GFX_ENV||{}, {pct:75});\n"
        + read('gfx_apply.js') + '\n' + read('gfx_fixed_640_native.js') + '\n'
    )
    return source + '\n' + lui + gfx


def emit(host: str, verify_only: bool = False) -> None:
    payload = {
        'HOST_SOURCE': host,
        'PARTY_SOURCE': read('party_bot_inject.js'),
        'BOTH_SIDES_SOURCE': read('native_ai_both_sides.js'),
        'VETERAN_SOURCE': read('native_ai_veteran_guard.js'),
        'PACK_SOURCE': read('pack_installed.js'),
        'PACK_FILES': json.loads(read('verdansk_pack_files.json')),
    }
    lines = [
        '/* Generated by build_play_runtime.py. Do not edit by hand. */',
        "export const PLAY_RUNTIME_KIND = 'wzm452-original-experimental-host-unverified';",
    ]
    for key, value in payload.items():
        lines.append(f'export const {key} = {json.dumps(value)};')
    text = '\n'.join(lines) + '\n'
    if verify_only:
        if not OUT.is_file() or OUT.read_text() != text:
            raise SystemExit('generated original host/AI payload is stale; regenerate explicitly before signing')
    else:
        OUT.write_text(text)
    with tempfile.TemporaryDirectory() as scratch:
        host_path = Path(scratch) / 'host.js'
        host_path.write_text(host)
        subprocess.run(['node', '--check', str(host_path)], check=True)
        for name in ('PARTY_SOURCE', 'BOTH_SIDES_SOURCE', 'VETERAN_SOURCE', 'PACK_SOURCE'):
            path = Path(scratch) / (name + '.js')
            path.write_text(payload[name])
            subprocess.run(['node', '--check', str(path)], check=True)
    print(f'{"verified" if verify_only else "wrote"} {OUT} ({OUT.stat().st_size} bytes), host {len(host)} chars')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true',
                        help='read-only: fail if generated JavaScript differs from original sources')
    args = parser.parse_args()
    emit(build_host(), verify_only=args.verify)


if __name__ == '__main__':
    sys.exit(main())
