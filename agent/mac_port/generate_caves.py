#!/usr/bin/env python3
import os
"""Generate caves.js: unused zero padding in libgame.so's code segment (after ret/b/br),
used by nearhook.js as relay space for hooks that Frida cannot place directly."""
import hashlib
import json
import struct
from pathlib import Path

LIBGAME = Path(os.environ.get('WZM_LIBGAME', 'input/libgame.so'))
OUT = Path(__file__).resolve().parent / 'caves.js'
RESERVED = (0x3cd7af0, 0x3cd7b80)   # cave/veneers used by the Mac scripts (lui_send, host, bots)


def main():
    data = LIBGAME.read_bytes()
    assert hashlib.sha256(data).hexdigest().startswith('c8f5e9df317b7442'), 'unexpected libgame.so'
    phoff = struct.unpack_from('<Q', data, 0x20)[0]
    phentsize, phnum = struct.unpack_from('<HH', data, 0x36)
    for i in range(phnum):
        t, fl, off, va, _pa, fs, _ms, _al = struct.unpack_from('<IIQQQQQQ', data, phoff + i * phentsize)
        if t == 1 and fl & 1 and fs > 0x1000000:
            break
    text = data[off:off + fs]
    word = lambda i: struct.unpack_from('<I', text, i)[0]
    ends = lambda x: x == 0xd65f03c0 or (x >> 26) == 0b000101 or (x & 0xfffffc1f) == 0xd61f0000
    caves, i, n = [], 0, len(text)
    while i < n - 4:
        if text[i:i + 4] != b'\0\0\0\0':
            i += 4
            continue
        j = i
        while j < n and text[j:j + 4] == b'\0\0\0\0':
            j += 4
        a = va + i
        vm_stub = i >= 8 and (word(i - 4) & 0xfffffc1f) == 0xd61f0000 and (word(i - 8) & 0x9f00001f) == 0x9000000f
        reserved = a <= RESERVED[1] and a + (j - i) >= RESERVED[0]
        if j - i >= 64 and i >= 4 and ends(word(i - 4)) and not reserved:
            caves.append([a + 16, (j - i) - 16])   # leave 16 bytes after the previous function
        i = j
    # Hook sites (all Mac scripts + this agent). A site is fragile when one of its first four
    # instructions branches/calls/returns: Frida then needs free memory within +-128 MB.
    import re
    src = (OUT.parent / 'mac_sources.js').read_text()
    m = re.search(r'export const PROBE_SITES = (\[[^\]]*\]);', src)
    sites = set(json.loads(m.group(1))) | {0x12a12f4, 0x2eaf78c, 0x337c1c0}
    def is_branch(x):
        return (x >> 26) in (0b000101, 0b100101) or (x & 0xff000010) == 0x54000000 or \
            (x & 0x7e000000) in (0x34000000, 0x36000000) or (x & 0xfffffc1f) in (0xd61f0000, 0xd63f0000, 0xd65f0000)
    fragile = []
    for s_ in sorted(sites):
        o = s_ - va
        if 0 <= o < n - 16 and any(is_branch(word(o + 4 * k)) for k in range(4)):
            fragile.append(s_)
    OUT.write_text('// GENERATED by generate_caves.py from libgame.so (sha c8f5e9df...). Zero padding after\n'
                   '// ret/b/br in the code segment; excludes the Mac scripts cave and VM-stub tails.\n'
                   'export const CAVES = ' + json.dumps(caves) + ';\n'
                   '// Hook sites that always go through a relay (same behaviour on every phone).\n'
                   'export const FRAGILE = ' + json.dumps(fragile) + ';\n')
    print(len(caves), 'caves', sum(c[1] for c in caves), 'bytes;', len(fragile), 'fragile sites:',
          ' '.join(hex(x) for x in fragile))


if __name__ == '__main__':
    main()
